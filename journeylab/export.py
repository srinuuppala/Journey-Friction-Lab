def _csv(df: pd.DataFrame, path: Path):
    df.to_csv(path, index=False, lineterminator="\n")


def _jsonl(df: pd.DataFrame, path: Path, chunk: int = 100_000):
    with open(path, "w", encoding="utf-8") as f:
        for i in range(0, len(df), chunk):
            s = df.iloc[i:i + chunk].to_json(orient="records", lines=True, force_ascii=False)
            f.write(s if s.endswith("\n") or not s else s + "\n")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _sql_literal(v):
    if v is None or (isinstance(v, float) and np.isnan(v)) or v is pd.NA:
        return "NULL"
    if isinstance(v, (bool, np.bool_)):
        return "1" if v else "0"
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, (float, np.floating)):
        return repr(float(v))
    return "'" + str(v).replace("'", "''") + "'"


def write_sql(tables: dict, outdir: Path, max_rows: int):
    (outdir / "schema.sql").write_text(ddl("sqlite"), encoding="utf-8")
    order = ["customer", "consent_event", "device", "identity_link", "page", "product", "experiment", "support_agent",
             "event_taxonomy", "session", "cart", "order", "cart_item", "order_line", "support_ticket",
             "experiment_assignment", "journey_event", "status_history", "journey_outcome"]
    big = []
    with open(outdir / "seed.sql", "w", encoding="utf-8") as f:
        f.write("-- Seed data generated by journeylab. Load schema.sql first.\nBEGIN TRANSACTION;\n")
        for name in order:
            df = tables[name]
            if len(df) > max_rows:
                big.append(name)
                f.write(f"-- {name}: {len(df):,} rows -> load data/{name}.csv with load_csv_postgres.sql "
                        f"or `python -m journeylab sqlite`\n")
                continue
            cols = ", ".join(f'"{c}"' for c in df.columns)
            vals = df.astype(object).where(df.notna(), None).itertuples(index=False, name=None)
            batch = []
            for row in vals:
                batch.append("(" + ", ".join(_sql_literal(v) for v in row) + ")")
                if len(batch) == 500:
                    f.write(f'INSERT INTO "{name}" ({cols}) VALUES\n' + ",\n".join(batch) + ";\n")
                    batch = []
            if batch:
                f.write(f'INSERT INTO "{name}" ({cols}) VALUES\n' + ",\n".join(batch) + ";\n")
        f.write("COMMIT;\n")
    with open(outdir / "load_csv_postgres.sql", "w", encoding="utf-8") as f:
        f.write("-- psql -f schema.sql; then run this from the dataset root (FKs are checked at COMMIT)\n"
                "-- Note: in PostgreSQL replace DEFERRABLE lines if needed; empty CSV fields load as NULL.\nBEGIN;\n")
        for name in order:
            f.write(f"\\copy \"{name}\" FROM 'data/{name}.csv' WITH (FORMAT csv, HEADER true);\n")
        f.write("COMMIT;\n")
    return big


def export(D, out: Path, formats=("csv", "json", "sql"), extra_reports: dict | None = None) -> dict:
    out = Path(out)
    for sub in ("data", "ground_truth", "derived", "reports", "sql"):
        (out / sub).mkdir(parents=True, exist_ok=True)
    for name in INPUT_TABLES:
        df = D.tables[name]
        if "csv" in formats:
            _csv(df, out / "data" / f"{name}.csv")
        if "json" in formats:
            _jsonl(df, out / "data" / f"{name}.jsonl")
    for name, df in D.truth.items():
        _csv(df, out / "ground_truth" / f"{name}.csv")
        _jsonl(df, out / "ground_truth" / f"{name}.jsonl")
    (out / "ground_truth" / "expected_findings.json").write_text(json.dumps(D.expected_findings, indent=2, sort_keys=True,
                                                                            default=str) + "\n")
    for name in DERIVED_EXPORTS:
        _csv(D.derived[name], out / "derived" / f"{name}.csv")
    (out / "derived" / "cross_channel_summary.json").write_text(json.dumps(D.derived["cross_channel_summary"], indent=2,
                                                                          sort_keys=True) + "\n")
    sc = {k: ({kk: vv for kk, vv in v.items() if kk != "mismatched_ids"} if isinstance(v, dict) else v)
          for k, v in D.derived["sessionization"].items()}
    (out / "derived" / "sessionization_check.json").write_text(json.dumps(sc, indent=2, sort_keys=True) + "\n")
    if "sql" in formats:
        write_sql(D.tables, out / "sql", D.meta["config"]["sql_insert_max_rows"])
    for name, content in (extra_reports or {}).items():
        p = out / "reports" / name
        p.write_text(content if isinstance(content, str) else json.dumps(content, indent=2, sort_keys=True, default=str) + "\n")
    return write_manifest(D, out, formats)


def write_manifest(D, out: Path, formats) -> dict:
    files = []
    for p in sorted(out.rglob("*")):
        if p.is_file() and p.name not in ("manifest.json",) and p.suffix != ".sqlite" and "reports/run_" not in str(p):
            rel = p.relative_to(out).as_posix()
            rows = None
            if p.suffix in (".csv",):
                with open(p, "rb") as f:
                    rows = sum(1 for _ in f) - 1
            elif p.suffix == ".jsonl":
                with open(p, "rb") as f:
                    rows = sum(1 for _ in f)
            files.append(dict(path=rel, bytes=p.stat().st_size, rows=rows, sha256=sha256(p)))
    cfg = D.meta["config"]
    man = dict(
        dataset="journey-friction-lab synthetic cross-channel journeys",
        generator_version=C.GENERATOR_VERSION, seed=cfg["seed"], scale=cfg["scale"], config=cfg,
        generator_command=f"python -m journeylab generate --scale {cfg['scale']} --seed {cfg['seed']} --out <dir>",
        formats=list(formats),
        environment=dict(python=sys.version.split()[0], numpy=np.__version__, pandas=pd.__version__,
                         platform=platform.platform()),
        provenance=dict(
            data_origin="100% synthetic, produced by the seeded simulator in journeylab/; no external or public dataset "
                        "was downloaded, copied or transformed.",
            personal_data="None. Customer IDs, e-mail hashes, IPs and anonymous IDs are synthetic tokens.",
            external_sources=[],
            schema_inspiration="Generic e-commerce analytics concepts (sessions, funnels, consent, identity graphs); "
                               "no third-party schema or data reused.",
            license="Generated data may be freely used and redistributed (CC0-1.0 intent)."),
        files=files)
    (out / "manifest.json").write_text(json.dumps(man, indent=2, sort_keys=True) + "\n")
    return man


