def load_tables(data_dir: Path) -> dict[str, pd.DataFrame]:
    data_dir = Path(data_dir)
    t = {}
    for tb in TABLES:
        p = data_dir / f"{tb.name}.csv"
        if not p.exists():
            continue
        df = pd.read_csv(p, dtype=str, keep_default_na=False, na_values=[""])
        for f in tb.fields:
            if f.name not in df:
                continue
            if f.type == "integer":
                df[f.name] = pd.to_numeric(df[f.name]).astype("Int64")
            elif f.type == "decimal":
                df[f.name] = pd.to_numeric(df[f.name]).astype(float)
            elif f.type == "boolean":
                df[f.name] = df[f.name].map({"True": True, "False": False, "true": True, "false": False})
        t[tb.name] = df
    return t


def load_truth(gt_dir: Path) -> dict:
    gt_dir = Path(gt_dir)
    tr = {}
    for name in ("anomalies", "session_labels"):
        df = pd.read_csv(gt_dir / f"{name}.csv", dtype=str, keep_default_na=False, na_values=[""])
        for c in df.columns:
            if c.startswith("has_") or c.startswith("device_has"):
                df[c] = df[c].map({"True": True, "False": False})
        tr[name] = df
    return tr


def sqlite_check(tables: dict, db_path: Path) -> dict:
    """Load every table into SQLite with FK enforcement and run PRAGMA foreign_key_check."""
    db_path = Path(db_path)
    if db_path.exists():
        db_path.unlink()
    con = sqlite3.connect(db_path)
    con.executescript(ddl("sqlite"))
    con.execute("PRAGMA foreign_keys = ON")
    counts = {}
    order = ["customer", "consent_event", "device", "identity_link", "page", "product", "experiment", "support_agent",
             "event_taxonomy", "session", "cart", "order", "cart_item", "order_line", "support_ticket",
             "experiment_assignment", "journey_event", "status_history", "journey_outcome"]
    con.execute("BEGIN")
    for name in order:
        df = tables[name]
        cols = ", ".join(f'"{c}"' for c in df.columns)
        q = f'INSERT INTO "{name}" ({cols}) VALUES ({", ".join("?" * len(df.columns))})'
        for i in range(0, len(df), 100_000):
            part = df.iloc[i:i + 100_000]
            rows = part.astype(object).where(part.notna(), None)
            con.executemany(q, ([(_py(v)) for v in r] for r in rows.itertuples(index=False, name=None)))
            del rows
        counts[name] = con.execute(f'SELECT COUNT(*) FROM "{name}"').fetchone()[0]
    con.execute("COMMIT")
    fk = con.execute("PRAGMA foreign_key_check").fetchall()
    joins = {
        "events_join_sessions": 'SELECT COUNT(*) FROM journey_event e JOIN session s USING(session_id)',
        "orders_join_carts_sessions": 'SELECT COUNT(*) FROM "order" o JOIN cart c USING(cart_id) JOIN session s ON s.session_id=o.session_id',
        "outcomes_join_sessions": 'SELECT COUNT(*) FROM journey_outcome o JOIN session s USING(session_id)',
    }
    jr = {k: con.execute(v).fetchone()[0] for k, v in joins.items()}
    con.close()
    return dict(row_counts=counts, foreign_key_violations=len(fk), join_counts=jr,
                joins_complete=jr["events_join_sessions"] == counts["journey_event"]
                and jr["orders_join_carts_sessions"] == counts["order"]
                and jr["outcomes_join_sessions"] == counts["journey_outcome"])


def _py(v):
    if isinstance(v, (np.integer,)):
        return int(v)
    if isinstance(v, (np.floating,)):
        return None if np.isnan(v) else float(v)
    if isinstance(v, (np.bool_,)):
        return bool(v)
    if isinstance(v, float) and np.isnan(v):
        return None
    return v
