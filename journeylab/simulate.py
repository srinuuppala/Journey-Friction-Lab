    def _gen_consent(self, c):
        """Consent history with explicit events (never overwritten)."""
        R = self.R
        evs = []
        created = c["created_at"]
        policy_v2 = C.ts("2026-06-01T00:00:00Z")
        src0 = {"web": "signup_form", "app": "app_prompt", "store": "store_form"}[c["signup_channel"]]
        ver = "v2" if created >= policy_v2 else "v1"
        lo = max(created, P0)

        def later(a, b):
            return a + int(R.random() * max(1, b - a))

        r = R.random()
        if r < 0.60:
            evs.append(("analytics", "granted", created, src0, ver))
            if R.random() < .12 and lo < P1 - 5 * DAY:
                wd = later(lo, P1 - 2 * DAY)
                evs.append(("analytics", "withdrawn", wd, "preference_center", ver))
                if R.random() < .35:
                    evs.append(("analytics", "granted", later(wd + DAY, P1), "cookie_banner", ver))
        elif r < 0.78:
            evs.append(("analytics", "denied", created, src0, ver))
            if R.random() < .20 and lo < P1 - 5 * DAY:
                evs.append(("analytics", "granted", later(lo, P1), "cookie_banner", ver))
        elif r < 0.88:
            pass  # no consent record at all -> "unknown" (treated as not consented)
        else:
            evs.append(("analytics", "granted", created, src0, ver))
            if created < policy_v2:
                evs.append(("analytics", "expired", policy_v2, "policy_update", "v1"))
                if R.random() < .55:
                    evs.append(("analytics", "granted", later(policy_v2, P1), "cookie_banner", "v2"))
        # marketing
        has_analytics = any(e[1] == "granted" for e in evs)
        if R.random() < (.55 if has_analytics else .15):
            evs.append(("marketing", "granted", created, src0, ver))
            if R.random() < .08 and lo < P1 - 5 * DAY:
                evs.append(("marketing", "withdrawn", later(lo, P1), "preference_center", ver))
        elif r < 0.88:
            evs.append(("marketing", "denied", created, src0, ver))
        evs.sort(key=lambda e: (e[2], e[0]))
        c["consent"] = {"analytics": [], "marketing": []}
        for ctype, action, at, src, v in evs:
            self.w.consent_events.append(dict(customer_idx=c["idx"], consent_type=ctype, action=action,
                                              effective_at=at, source=src, policy_version=v))
        for ctype in ("analytics", "marketing"):
            intervals, open_at = [], None
            for e in evs:
                if e[0] != ctype:
                    continue
                if e[1] == "granted" and open_at is None:
                    open_at = e[2]
                elif e[1] != "granted" and open_at is not None:
                    intervals.append((open_at, e[2]))
                    open_at = None
            if open_at is not None:
                intervals.append((open_at, 1 << 62))
            c["consent"][ctype] = intervals

    def consent_active(self, cust: int, ctype: str, t: int) -> bool:
        for a, b in self.w.customers[cust]["consent"][ctype]:
            if a <= t < b:
                return True
        return False

    # ---------------------------------------------------------- session setup
    def app_version(self, dev, t):
        v = C.APP_RELEASES[0][0]
        for ver, rel in C.APP_RELEASES:
            if rel + dev["update_lag"] <= t:
                v = ver
        return v

    def ip_hash(self, dev, t):
        return "IPH-%08x" % (crc(f"{dev['ip_salt']}:{t // DAY}") & 0xFFFFFFFF)

    def user_agent(self, dev, app_ver):
        if dev["platform"] == "app":
            return f"ShopApp/{app_ver} ({dev['os']})"
        return f"Mozilla/5.0 ({dev['os']}) {dev['browser']}"

    def assign_variants(self, dev_idx, channel, t):
        out = {}
        for e in self.w.experiments:
            if e["status"] == "draft":
                continue
            if e["channel"] not in ("all", channel):
                continue
            if not (e["start_ms"] <= t < e["end_ms"]):
                continue
            bucket = crc(f"{self.cfg.seed}:{dev_idx}:{e['name']}") % 1000
            out[e["idx"]] = "treatment" if bucket < e["allocation_treatment"] * 1000 else "control"
        return out

    def new_session(self, kind, channel, dev_idx, person, start, **kw):
        s = dict(idx=len(self.w.sessions), kind=kind, channel=channel, device=dev_idx, start=start,
                 _person=person, _actor="bot" if kind == "bot" else "human", _bot_type=None, ticket=-1)
        s.update(kw)
        self.w.sessions.append(s)
        return s

    def plan_human(self):
        R, w = self.R, self.w
        for _ in range(40):
            if R.random() < self.cfg.customer_device_session_share:
                ci = bisect.bisect_left(self.cust_cum, R.random() * self.cust_cum[-1])
                cust = w.customers[min(ci, len(w.customers) - 1)]
                devs = cust["devices"]
                dev = w.devices[R.choices(devs, weights=[w.devices[d]["activity"] for d in devs])[0]]
                person = cust["idx"]
            else:
                di = bisect.bisect_left(self.anon_cum, R.random() * self.anon_cum[-1])
                dev = self.anon_devs[min(di, len(self.anon_devs) - 1)]
                person = -1
            lo = max(P0, dev["first_seen"])
            hi = P1 - 2 * HOUR
            if lo >= hi - HOUR:
                continue
            start = self.sample_time(lo, hi, dev["country"])
            if self.device_free(dev["idx"], start):
                return dev, person, start
        return None

    def build_context(self, dev, person, start, kind="human"):
        R, w = self.R, self.w
        channel = dev["platform"]
        app_ver = self.app_version(dev, start) if channel == "app" else None
        geo = dev["country"] if R.random() > .05 else R.choice(list(C.COUNTRIES))
        can_auth = person >= 0 and start >= w.customers[person]["created_at"]
        auth0 = can_auth and R.random() < (.85 if channel == "app" else .25)
        mkt = person >= 0 and self.consent_active(person, "marketing", start)
        if channel == "web":
            src = self.pick({"direct": .28, "organic_search": .30, "paid_search": .15, "social": .10,
                             "referral": .07, "email": .10 if mkt else 0.0})
        else:
            src = self.pick({"direct": .62, "push": .25 if mkt else 0.0, "deep_link": .13})
        campaign = None
        if src in ("paid_search", "social", "email", "push"):
            m = (start - P0) // (30 * DAY) + 1
            campaign = f"CMP-2026{min(m, 10):02d}-{src.upper().replace('_', '')}"
        return dict(app_version=app_ver, geo_country=geo, can_auth=can_auth,
                    auth_at_start=auth0, traffic_source=src, utm_campaign=campaign,
                    landing_state=self.pick(LANDING[src]),
                    user_agent=self.user_agent(dev, app_ver or ""),
                    ip_hash=self.ip_hash(dev, start) if R.random() > .04 else "IPH-nat%04x" % R.randrange(30),
                    variants=self.assign_variants(dev["idx"], channel, start))

    # ------------------------------------------------------------ incidents
    def incident(self, iid, s, t):
        inc = self._inc[iid]
        if not (inc["start_ms"] <= t < inc["end_ms"]) or s["channel"] != inc["channel"]:
            return False
        if "app_version" in inc and s.get("app_version") != inc["app_version"]:
            return False
        if "app_version_prefix" in inc and not (s.get("app_version") or "").startswith(inc["app_version_prefix"]):
            return False
        if "os" in inc and self.w.devices[s["device"]]["os"] != inc["os"]:
            return False
        if "geo_country" in inc and s["geo_country"] not in inc["geo_country"]:
            return False
        return True

    def page_load(self, s, state, t):
        med = LOAD_MEDIAN_MS[state] * (0.7 if s["channel"] == "app" else 1.0)
        load = med * math.exp(0.45 * self.R.gauss(0, 1))
        if self.R.random() < .01:
            load *= 4
        if state == "search" and self.incident("INC-2026-003", s, t):
            load *= self._inc["INC-2026-003"]["latency_multiplier"]
        return int(load)

    def dwell(self, state, app):
        d = DWELL_MEDIAN_S[state] * SEC * (0.75 if app else 1.0) * math.exp(0.85 * self.R.gauss(0, 1))
        return int(d)

    def page(self, channel, state, category=None, topic=None):
        ptype = STATE_PAGE_TYPE[state]
        key = category if ptype == "category" else topic if ptype == "help" else None
        return self.page_lookup[(channel, ptype, key)]

    def pick_product(self, t, category=None):
        R = self.R
        for _ in range(8):
            cat = category or R.choices(self.cat_names, weights=self.cat_weights)[0]
            plist, cum = self.cat_products[cat]
            if not plist:
                category = None
                continue
            p = plist[min(bisect.bisect_left(cum, R.random() * cum[-1]), len(plist) - 1)]
            if p["launched_at"] <= t and (p["discontinued_at"] is None or t < p["discontinued_at"]):
                return p
            category = None if R.random() < .5 else category
        for p in self.w.products:  # deterministic fallback
            if p["launched_at"] <= t and (p["discontinued_at"] is None or t < p["discontinued_at"]):
                return p
        return self.w.products[0]

    def add_link(self, dev, cust, method, at, conf, source):
        key = (dev, cust)
        if key in self.link_index:
            ln = self.w.links[self.link_index[key]]
            if method == "login" and (ln["link_method"] != "login" or at < ln["valid_from"]):
                ln.update(link_method=method, valid_from=at, confidence=conf, source_system=source)
            elif method == ln["link_method"] and at < ln["valid_from"]:
                ln["valid_from"] = at
            return
        self.link_index[key] = len(self.w.links)
        self.w.links.append(dict(device_idx=dev, customer_idx=cust, link_method=method, confidence=conf,
                                 valid_from=at, valid_to=None, source_system=source, _bogus=False))

    # ------------------------------------------------------------ human run
    def run_human(self, s, allow_spawn: bool):
        R, ev, w = self.R, self.ev, self.w
        rr = R.random
        si, ch = s["idx"], s["channel"]
        app = ch == "app"
        dev = w.devices[s["device"]]
        person = s["_person"]
        cust = person if s["auth_at_start"] else -1
        t = s["start"]
        view = EV["screen_view"] if app else EV["page_view"]
        mult = {}
        for e_idx, var in s["variants"].items():
            if var == "treatment":
                for k, v in C.EXPERIMENT_TRUTH[w.experiments[e_idx]["name"]].items():
                    if "->" in k:
                        mult[k] = v
        seg = w.customers[person]["segment"] if person >= 0 else "anonymous"
        atc_boost = (1.15 if app else 1.0) * {"vip": 1.3, "regular": 1.05, "new": 1.0, "anonymous": .85}[seg]
        mult["product->add_to_cart"] = mult.get("product->add_to_cart", 1.0) * atc_boost
        mult["cart->shipping"] = mult.get("cart->shipping", 1.0) * (1.1 if app else 1.0)
        if cust >= 0 or not s["can_auth"]:
            mult["home->login"] = 0.0
        intent = s.get("intent")
        if intent:                       # returning to finish an earlier journey
            mult["product->add_to_cart"] *= 2.6
            mult["cart->shipping"] = mult.get("cart->shipping", 1.0) * 1.6
            mult["product->EXIT"] = .6

        category = R.choices(self.cat_names, weights=self.cat_weights)[0]
        topic = R.choice(C.HELP_TOPICS)
        state = s["landing_state"]
        prev = None
        product = None
        cart = None           # cart dict
        items = {}            # product idx -> cart item dict
        pay_attempts = ship_attempts = atc_attempts = 0
        flags = dict(pay_error=False, ship_error=False, atc_fail=False)
        order = None
        spawned = False
        n_pages = 0
        hard_end = s["start"] + C.MAX_SESSION_MS - 40 * MIN

        def E(et, page=-1, **kw):
            return ev.add(si, EV[et] if isinstance(et, str) else et, kw.pop("at", t), page=page, cust=cust, **kw)

        E("session_start", self.page(ch, state, category, topic))
        t += int(200 + rr() * 800)
        while n_pages < 60 and t < hard_end:
            n_pages += 1
            if state == "product":
                if intent and n_pages <= 2 and intent.get("product") is not None:
                    p = w.products[intent["product"]]
                    if not (p["launched_at"] <= t and (p["discontinued_at"] is None or t < p["discontinued_at"])):
                        p = self.pick_product(t, p["category"])
                else:
                    p = self.pick_product(t, category if prev in ("category", "product") and rr() < .7 else None)
                product, category = p, p["category"]
            pg = self.page(ch, state, category, topic)
            load = self.page_load(s, state, t)
            ev.add(si, view, t, page=pg, cust=cust, load=load)
            t += load
            if rr() < .004:
                E("page_error", pg, http=503, err=ERR["HTTP_503"])
                if rr() < .5:
                    break
            if load > 4000 and rr() < min(.45, .12 + (load - 4000) / 12000):
                break   # latency-driven abandonment
            dwell = self.dwell(state, app)
            if rr() < .003:   # boundary coverage: long idle gap close to the 30-min timeout
                dwell = int(20 * MIN + rr() * 14 * MIN)
            if dwell > C.INACTIVITY_TIMEOUT_MS - 30 * SEC:
                break   # user went idle -> session times out
            # engagement events inside the dwell window
            n_eng = self.pois(SCROLL_MEAN.get(state, .3)) + self.pois(CLICK_MEAN.get(state, .2))
            if n_eng:
                offs = sorted(int(rr() * dwell * .9) + 1 for _ in range(n_eng))
                for k, o in enumerate(offs):
                    ev.add(si, EV["scroll"] if k % 2 == 0 else EV["click"], t + o, page=pg, cust=cust)
            # state-specific actions ---------------------------------------
            if state == "search":
                E("search", pg, at=t + int(dwell * .1) + 1)
            elif state == "product":
                E("product_view", pg, product=product["idx"], at=t + 1)
            elif state == "cart":
                E("cart_view", pg, cart=cart["idx"], at=t + 1)
            elif state == "help":
                E("help_view", pg, at=t + 1)
            elif state == "login":
                t += dwell
                if rr() < .96:
                    cust = person
                    E("login", pg)
                    self.add_link(s["device"], person, "login", t, 1.0, "auth_service")
                else:
                    E("login_failed", pg, http=401, err=ERR["AUTH_INVALID_CREDENTIALS"])
                state, prev = (prev or "home"), "login"
                if state in ("login", "shipping", "payment"):
                    state = "home"
                t += int(300 + rr() * 1500)
                continue
            elif state == "shipping":
                if cust < 0 and s["can_auth"] and rr() < .55:
                    t += int(5 * SEC + rr() * 20 * SEC)
                    cust = person
                    E("login", pg)
                    self.add_link(s["device"], person, "login", t, 1.0, "auth_service")
                t += dwell
                err_p = self._inc["INC-2026-002"]["error_rate"] if self.incident("INC-2026-002", s, t) else .02
                ship_attempts += 1
                if rr() < err_p:
                    flags["ship_error"] = True
                    E("shipping_validation_error", pg, cart=cart["idx"], http=422, err=ERR["ADDR_VALIDATION_FAILED"])
                    t += int(1 * SEC + rr() * 4 * SEC)
                    u = rr()
                    if ship_attempts < 3 and u < .45:
                        continue
                    if u < .55:
                        prev, state, topic = state, "help", "delivery"
                        continue
                    break
                E("shipping_info_submitted", pg, cart=cart["idx"])
                t += int(300 + rr() * 1500)
                nxt = self.pick(TRANSITIONS["shipping"], mult, "shipping")
                if nxt == "EXIT":
                    break
                prev, state = state, nxt
                if nxt == "help":
                    topic = "delivery"
                continue
            elif state == "payment":
                t += dwell
                pay_attempts += 1
                E("payment_info_submitted", pg, cart=cart["idx"])
                t += int(1.5 * SEC + rr() * 6 * SEC)
                inc1 = self.incident("INC-2026-001", s, t)
                if rr() < (.45 if inc1 else .03):
                    flags["pay_error"] = True
                    code = "PAY_GATEWAY_TIMEOUT" if inc1 else R.choice(["PAY_DECLINED", "PAY_DECLINED", "PAY_3DS_FAILED"])
                    E("payment_error", pg, cart=cart["idx"], http=504 if inc1 else 402, err=ERR[code])
                    t += int(2 * SEC + rr() * 10 * SEC)
                    u = rr()
                    if pay_attempts < 3 and u < .5:
                        continue
                    if u < .62:
                        prev, state, topic = state, "help", "payments"
                        continue
                    break
                order = self.create_order(s, cart, items, cust, t)
                mult["product->add_to_cart"] = 0.0
                E("purchase", pg, cart=cart["idx"], order=order["idx"], value=order["total"])
                prev, state = state, "confirmation"
                t += int(500 + rr() * 2000)
                continue
            t += dwell
            # transitions ----------------------------------------------------
            tw = TRANSITIONS[state]
            if state == "product" and (cart is None or order is not None):
                tw = {k: v for k, v in tw.items() if k != "cart"}
            nxt = self.pick(tw, mult, state)
            if nxt == "add_to_cart":
                while True:
                    atc_attempts += 1
                    if self.incident("INC-2026-004", s, t) and rr() < .5:
                        flags["atc_fail"] = True
                        E("add_to_cart_failed", pg, product=product["idx"], http=500, err=ERR["CART_API_500"])
                        for _ in range(1 + int(rr() * 3)):   # rage clicks
                            t += int(400 + rr() * 1500)
                            E("click", pg)
                        nxt2 = self.pick(TRANSITIONS["atc_failed"])
                        if nxt2 == "add_to_cart" and atc_attempts < 4:
                            t += int(1 * SEC + rr() * 3 * SEC)
                            continue
                        nxt = nxt2 if nxt2 != "add_to_cart" else "EXIT"
                        break
                    if cart is None:
                        cart = dict(idx=len(w.carts), session=si, created_at=t, checkout_at=None,
                                    order=-1, cust=-1, status="open")
                        w.carts.append(cart)
                    q = R.choices([1, 2, 3], weights=[.80, .15, .05])[0]
                    pid = product["idx"]
                    if pid in items and items[pid]["removed_at"] is None:
                        items[pid]["quantity"] += q
                    else:
                        items[pid] = dict(idx=len(w.cart_items), cart_idx=cart["idx"], product_idx=pid,
                                          quantity=q, unit_price=product["list_price"], added_at=t, removed_at=None)
                        w.cart_items.append(items[pid])
                    E("add_to_cart", pg, product=pid, cart=cart["idx"], qty=q, value=round(q * product["list_price"], 2))
                    nxt = self.pick(TRANSITIONS["post_atc"])
                    break
            if nxt == "REMOVE":
                active = [it for it in items.values() if it["removed_at"] is None]
                if active:
                    it = active[int(rr() * len(active))]
                    it["removed_at"] = t
                    E("remove_from_cart", pg, product=it["product_idx"], cart=cart["idx"], qty=it["quantity"],
                      value=round(it["quantity"] * it["unit_price"], 2))
                nxt = "cart" if any(i["removed_at"] is None for i in items.values()) else "product"
            if nxt == "shipping":
                if cart is None or not any(i["removed_at"] is None for i in items.values()):
                    nxt = "product"
                else:
                    if cart["checkout_at"] is None:
                        cart["checkout_at"] = t
                    E("checkout_start", pg, cart=cart["idx"])
            if nxt == "CONTACT":
                E("contact_support_click", pg)
                if allow_spawn and not spawned:
                    reason = ("payment_issue" if flags["pay_error"] else "checkout_issue" if flags["ship_error"]
                              else "technical_issue" if flags["atc_fail"] else
                              R.choice(["product_question", "product_question", "account_access"]))
                    spawned = self.spawn_support(s, person, t + int(MIN + rr() * 14 * MIN), "chat", reason,
                                                 order=order["idx"] if order else -1)
                if rr() < .7:
                    break
                nxt = "home"
            if nxt == "EXIT":
                break
            if nxt == "help" and state != "help":
                topic = R.choice(C.HELP_TOPICS)
            prev, state = state, nxt
            t += int(300 + rr() * 1700)
        # session closed ---------------------------------------------------
        s["end_planned"] = t
        s["flags"] = flags
        if cart is not None:
            cart["cust"] = cust
            if order is None:
                cart["status"] = "abandoned"
            self.history("cart", cart["idx"], None, "open", cart["created_at"])
            if cart["checkout_at"]:
                self.history("cart", cart["idx"], "open", "checkout_started", cart["checkout_at"])
            last = "checkout_started" if cart["checkout_at"] else "open"
            if order is not None:
                self.history("cart", cart["idx"], last, "converted", order["order_ts"])
            else:
                self.history("cart", cart["idx"], last, "abandoned", t + C.INACTIVITY_TIMEOUT_MS)
        # support contact after payment failure without in-session contact
        if flags["pay_error"] and order is None and not spawned and allow_spawn and rr() < .18:
            spawned = self.spawn_support(s, person, t + int(30 * MIN + rr() * 23 * HOUR),
                                         R.choice(["chat", "phone"]), "payment_issue")
        if order is not None and allow_spawn and not spawned:
            self.order_followups(s, order, person)
        # return-to-buy behaviour after abandonment (cross-session / cross-device)
        if order is None and cart is not None and not s.get("intent") and allow_spawn:
            p_ret = (.30 if cart["checkout_at"] else .12) * (0.5 if flags["pay_error"] or flags["ship_error"] else 1.0)
            if rr() < p_ret:
                first_item = min(items.values(), key=lambda x: x["added_at"])["product_idx"] if items else None
                self.spawn_return(s, person, t + int(2 * HOUR + rr() * 4 * DAY), first_item, "abandonment")
        return s

    def budget_ok(self, k=1):
        return len(self.w.sessions) + k <= self.n_nonbot_target

    def spawn_return(self, origin, person, at, product_idx, reason):
        """Same person comes back (often on another device/channel) to finish the purchase."""
        R, w = self.R, self.w
        if not self.budget_ok(1) or at >= P1 - 3 * HOUR:
            return False
        if person >= 0:
            devs = list(w.customers[person]["devices"])
            other = [d for d in devs if w.devices[d]["platform"] != origin.get("channel")]
            cands = (other if other and R.random() < .55 else devs)
        else:
            cands = [origin["device"]] if origin.get("device", -1) >= 0 else []
        for _ in range(6):
            if not cands:
                return False
            dev = w.devices[cands[int(R.random() * len(cands))]]
            if dev["first_seen"] <= at and self.device_free(dev["idx"], at):
                break
            at += int(9 * HOUR)
            if at >= P1 - 3 * HOUR:
                return False
        else:
            return False
        ctx = self.build_context(dev, person, at)
        ctx["landing_state"] = "product" if product_idx is not None else "home"
        if ctx["traffic_source"] not in ("email", "push"):
            ctx["traffic_source"] = "direct"
            ctx["utm_campaign"] = None
        s = self.new_session("human", dev["platform"], dev["idx"], person, at, **ctx)
        s["intent"] = dict(product=product_idx, reason=reason, origin=origin["idx"])
        self.reserve_device(dev["idx"], at, s["idx"])
        self.run_human(s, allow_spawn=False)
        return True

    # ---------------------------------------------------------------- orders
    def create_order(self, s, cart, items, cust, t):
        R, w = self.R, self.w
        lines = [it for it in sorted(items.values(), key=lambda x: x["added_at"]) if it["removed_at"] is None]
        subtotal = round(sum(round(it["quantity"] * it["unit_price"], 2) for it in lines), 2)
        discount = round(subtotal * .10, 2) if R.random() < .12 else 0.0
        person = s["_person"]
        ship_country = w.customers[person]["country"] if cust >= 0 else s["geo_country"]
        taxable = round(subtotal - discount, 2)
        tax = round(taxable * C.COUNTRIES[ship_country][2], 2)
        shipping = 0.0 if taxable >= 50 else 4.99
        total = round(taxable + tax + shipping, 2)
        pm = ["card", "wallet", "bnpl"] + (["upi"] if ship_country == "IN" else [])
        pmw = [.55, .20, .10] + ([.15] if ship_country == "IN" else [])
        o = dict(idx=len(w.orders), cart_idx=cart["idx"], session=s["idx"], cust=cust, order_ts=t,
                 ship_country=ship_country, subtotal=subtotal, discount=discount, tax=tax, shipping=shipping,
                 total=total, currency="USD", payment_method=R.choices(pm, weights=pmw)[0],
                 item_count=sum(it["quantity"] for it in lines))
        w.orders.append(o)
        for n, it in enumerate(lines, 1):
            w.order_lines.append(dict(order_idx=o["idx"], line_no=n, product_idx=it["product_idx"],
                                      quantity=it["quantity"], unit_price=it["unit_price"],
                                      line_amount=round(it["quantity"] * it["unit_price"], 2)))
        cart["order"] = o["idx"]
        cart["status"] = "converted"
        # lifecycle (explicit history rows; current status = last row <= snapshot)
        st = "placed"
        self.history("order", o["idx"], None, "placed", t)
        paid = t + int(2 * SEC + R.random() * 18 * SEC)
        self.history("order", o["idx"], "placed", "paid", paid)
        st = "paid"
        o["_shipped"] = o["_delivered"] = o["_refunded"] = None
        if R.random() < .04:
            at = paid + int(HOUR + R.random() * 2 * DAY)
            if self.history("order", o["idx"], "paid", "cancelled", at, "customer"):
                st = "cancelled"
        else:
            shipped = paid + int(DAY + R.random() * 2 * DAY)
            if self.history("order", o["idx"], "paid", "shipped", shipped):
                st, o["_shipped"] = "shipped", shipped
                delivered = shipped + int(2 * DAY + R.random() * 4 * DAY)
                if self.history("order", o["idx"], "shipped", "delivered", delivered, "carrier"):
                    st, o["_delivered"] = "delivered", delivered
                    if R.random() < .03:
                        ref = delivered + int(3 * DAY + R.random() * 12 * DAY)
                        if self.history("order", o["idx"], "delivered", "refunded", ref, "support_agent"):
                            st, o["_refunded"] = "refunded", ref
        o["status"] = st
        return o

    def order_followups(self, s, o, person):
        R = self.R
        if o["_refunded"] and R.random() < .4:
            self.spawn_support(s, person, o["_refunded"] - int(R.random() * 2 * DAY), R.choice(["chat", "phone"]),
                               "refund_request", order=o["idx"])
        elif o["_shipped"] and R.random() < .035:
            end = (o["_delivered"] or o["_shipped"] + 4 * DAY) + 3 * DAY
            at = o["_shipped"] + 2 * DAY + int(R.random() * max(1, end - o["_shipped"] - 2 * DAY))
            self.spawn_support(s, person, at, R.choice(["chat", "phone"]), "delivery_issue", order=o["idx"])

    # --------------------------------------------------------------- support
    def spawn_support(self, origin, person, at, medium, reason, order=-1):
        if at >= P1 - HOUR:
            return False
        w = self.w
        cust = person if person >= 0 and at >= w.customers[person]["created_at"] else -1
        prio = {"payment_issue": "high", "refund_request": "high", "checkout_issue": "medium",
                "technical_issue": "medium", "delivery_issue": "medium"}.get(reason, "low")
        tk = dict(idx=len(w.tickets), cust=cust, origin_session=origin["idx"] if origin else -1, order=order,
                  medium=medium, category=reason, priority=prio, opened_at=at, first_response_at=None,
                  escalated_at=None, resolved_at=None, closed_at=None, agent=-1, csat=None,
                  status="open", first_session=-1, _person=person)
        w.tickets.append(tk)
        self.history("ticket", tk["idx"], None, "open", at, "customer")
        self.run_support(tk, origin, at, follow_up=False)
        return True

    def run_support(self, tk, origin, at, follow_up):
        R, ev, w = self.R, self.ev, self.w
        dev = origin["device"] if (origin and tk["medium"] == "chat") else -1
        s = self.new_session("support", "support", dev, tk["_person"], at, ticket=tk["idx"],
                             support_medium=tk["medium"], geo_country=origin["geo_country"] if origin else None,
                             user_agent="SupportWidget/3.4" if tk["medium"] == "chat" else None,
                             ip_hash=self.ip_hash(w.devices[dev], at) if dev >= 0 else None,
                             traffic_source="support", utm_campaign=None, app_version=None, variants={},
                             landing_state=None)
        if tk["first_session"] < 0:
            tk["first_session"] = s["idx"]
        si, cust, t = s["idx"], tk["cust"], at
        agent = R.choice(self.tier2 if follow_up else self.tier1)
        tid = tk["idx"]
        if not follow_up:
            ev.add(si, EV["ticket_created"], t, ticket=tid, cust=cust)
        else:
            ev.add(si, EV["message_customer"], t, ticket=tid, cust=cust)
        wait = int((90 if tk["medium"] == "chat" else 240) * SEC * math.exp(.7 * R.gauss(0, 1)))
        t += wait
        ev.add(si, EV["agent_assigned"], t, ticket=tid, cust=cust)
        if tk["first_response_at"] is None:
            tk["first_response_at"] = t
            tk["agent"] = agent
            self.history("ticket", tid, "open", "assigned", t, "support_agent")
        for k in range(2 + int(R.random() * 7)):
            t += int(15 * SEC + R.random() * 105 * SEC)
            ev.add(si, EV["message_customer" if k % 2 == 0 else "message_agent"], t, ticket=tid, cust=cust)
        t += int(20 * SEC + R.random() * 60 * SEC)
        p_res = .90 if follow_up else {"refund_request": .80, "payment_issue": .62}.get(tk["category"], .74)
        if R.random() < p_res:
            ev.add(si, EV["ticket_resolved"], t, ticket=tid, cust=cust)
            tk["resolved_at"] = t
            self.history("ticket", tid, "escalated" if follow_up else "assigned", "resolved", t, "support_agent")
            tk["status"] = "resolved"
            closed = t + 2 * DAY
            if self.history("ticket", tid, "resolved", "closed", closed):
                tk["closed_at"], tk["status"] = closed, "closed"
            if (tk["category"] in ("payment_issue", "checkout_issue", "technical_issue") and origin is not None
                    and origin.get("kind") == "human" and R.random() < .40):
                self.spawn_return(origin, tk["_person"], t + int(30 * MIN + R.random() * 2 * DAY), None, "support_resolved")
            if R.random() < .55:
                noise = R.choice([-1, 0, 0, 0, 1])
                score = 5 - (wait > 5 * MIN) - (1 if follow_up else 0) - (tk["category"] in ("payment_issue", "checkout_issue")) + noise
                score = max(1, min(5, score))
                t += int(10 * SEC + R.random() * 50 * SEC)
                ev.add(si, EV["csat_submitted"], t, ticket=tid, cust=cust, value=float(score))
                tk["csat"] = score
        elif follow_up:
            ev.add(si, EV["message_agent"], t, ticket=tid, cust=cust)   # still pending with tier-2
        else:
            ev.add(si, EV["ticket_escalated"], t, ticket=tid, cust=cust)
            tk["escalated_at"] = t
            tk["status"] = "escalated"
            self.history("ticket", tid, "assigned", "escalated", t, "support_agent")
            nxt = t + int(DAY + R.random() * 3 * DAY)
            if not follow_up and nxt < P1 - HOUR and self.count_nonbot() < self.n_nonbot_target:
                self.run_support(tk, origin, nxt, follow_up=True)
        s["end_planned"] = t
        s["flags"] = {}

    def count_nonbot(self):
        return len(self.w.sessions)

    # ------------------------------------------------------------------ main
    def run(self) -> World:
        self._inc = {i["incident_id"]: i for i in C.INCIDENTS}
        self.gen_master()
        target = self.n_nonbot_target
        while len(self.w.sessions) < target:
            plan = self.plan_human()
            if plan is None:
                continue
            dev, person, start = plan
            remaining = target - len(self.w.sessions)
            ctx = self.build_context(dev, person, start)
            s = self.new_session("human", dev["platform"], dev["idx"], person, start, **ctx)
            self.reserve_device(dev["idx"], start, s["idx"])
            self.run_human(s, allow_spawn=remaining >= 6)
        self.post_links()
        self.w.baseline_event_count = len(self.ev)
        return self.w

    def post_links(self):
        """E-mail click links and legitimate probabilistic links (derived from sessions)."""
        R, w = self.R, self.w
        for s in w.sessions:
            if s["kind"] == "human" and s["traffic_source"] == "email" and s["_person"] >= 0:
                self.add_link(s["device"], s["_person"], "email_click", s["start"], 0.95, "email_service")
        for d in w.devices[: self.n_customer_devices]:
            if len(d["owners"]) != 1:
                continue
            sess = self.device_sessions.get(d["idx"])
            if not sess or (d["idx"], d["owners"][0]) in self.link_index:
                continue
            if R.random() < .30:
                at = max(w.sessions[sess[min(1, len(sess) - 1)]]["start"], w.customers[d["owners"][0]]["created_at"])
                conf = round(.5 + .5 * R.betavariate(5, 2), 3)
                method, src = (("probabilistic_match", "identity_graph") if R.random() < .75
                               else ("cookie_sync", "cdp_sync"))
                self.add_link(d["idx"], d["owners"][0], method, at, conf, src)
