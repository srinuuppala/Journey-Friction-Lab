def crc(s: str) -> int:
    return zlib.crc32(s.encode("utf-8"))


class EventBuffer:
    """Columnar, append-only event store (compact typed arrays)."""
    INT_COLS = ("sess", "etype", "ts", "page", "product", "cart", "order", "ticket",
                "cust", "load", "http", "err", "qty")

    def __init__(self):
        for c in self.INT_COLS:
            setattr(self, c, array("q"))
        self.value = array("d")

    def __len__(self):
        return len(self.ts)

    def add(self, sess, etype, ts, page=-1, product=-1, cart=-1, order=-1, ticket=-1,
            cust=-1, load=-1, http=0, err=0, qty=0, value=NAN):
        self.sess.append(sess); self.etype.append(etype); self.ts.append(int(ts))
        self.page.append(page); self.product.append(product); self.cart.append(cart)
        self.order.append(order); self.ticket.append(ticket); self.cust.append(cust)
        self.load.append(load); self.http.append(http); self.err.append(err)
        self.qty.append(qty); self.value.append(value)
        return len(self.ts) - 1


