    # ------------------------------------------------------------------ utils
    def pick(self, weights: dict, mult: dict | None = None, prefix: str = ""):
        R = self.R
        items = []
        total = 0.0
        for k, wt in weights.items():
            if mult:
                wt *= mult.get(f"{prefix}->{k}", 1.0)
            if wt > 0:
                total += wt
                items.append((k, total))
        u = R.random() * total
        for k, cum in items:
            if u < cum:
                return k
        return items[-1][0]

    def pois(self, lam: float) -> int:
        if lam <= 0:
            return 0
        L = math.exp(-lam)
        k, p = 0, 1.0
        while True:
            p *= self.R.random()
            if p < L:
                return k
            k += 1

    def _day_weights(self):
        n_days = (P1 - P0) // DAY
        ws = []
        for d in range(n_days):
            t = P0 + d * DAY
            wd = ((d + 3) % 7)  # 2026-01-01 is a Thursday -> wd 3 = Thu (Mon=0)
            w = 0.85 + 0.30 * d / n_days
            if wd >= 5:
                w += 0.20
            for a, b, m in SALES:
                if a <= t < b:
                    w *= m
            ws.append(w)
        self.day_w = ws
        self.day_wmax = max(ws)

    def sample_time(self, lo: int, hi: int, country: str, flat: bool = False) -> int:
        R = self.R
        off = int(C.COUNTRIES[country][1] * HOUR)
        for _ in range(50):
            t = lo + int(R.random() * (hi - lo))
            d = (t - P0) // DAY
            if 0 <= d < len(self.day_w) and R.random() > self.day_w[d] / self.day_wmax:
                continue
            if flat:
                return t
            local = t + off
            local_day = (local // DAY) * DAY
            hour = R.choices(HOURS, cum_weights=DIURNAL_CUM)[0]
            t2 = local_day + hour * HOUR + int(R.random() * HOUR) - off
            if lo <= t2 < hi:
                return t2
        return lo + int(R.random() * (hi - lo))

    def device_free(self, dev: int, start: int) -> bool:
        lst = self.device_starts.get(dev)
        if not lst:
            return True
        i = bisect.bisect_left(lst, start)
        gap = C.DEVICE_SESSION_SPACING_MS
        if i < len(lst) and lst[i] - start < gap:
            return False
        if i > 0 and start - lst[i - 1] < gap:
            return False
        return True

    def reserve_device(self, dev: int, start: int, sess: int):
        bisect.insort(self.device_starts.setdefault(dev, []), start)
        self.device_sessions.setdefault(dev, []).append(sess)

    def history(self, entity_type, entity_idx, from_status, to_status, at, actor="system"):
        if at <= SNAPSHOT_TS:
            self.w.status_history.append(dict(entity_type=entity_type, entity_idx=entity_idx,
                                              from_status=from_status, to_status=to_status,
                                              changed_at=at, changed_by=actor))
            return True
        return False

