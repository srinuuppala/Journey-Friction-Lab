"""Baseline world simulation (valid records only).

Order of generation (parents before children):
  1. Customer, ConsentEvent (history), Device (+ household sharing), Product,
     Page, Experiment, SupportAgent                       -> master data
  2. Session -> JourneyEvent -> Cart/CartItem -> Order/OrderLine -> SupportTicket
     generated by a per-session state machine            -> transactions/events
  3. IdentityLink records derived from what happened (logins, e-mail clicks,
     probabilistic matches) and StatusHistory for every lifecycle change.

All entities use *internal integer keys* here.  Public IDs (CUS-000001, ...)
are assigned once, deterministically, in ``finalize.py`` after edge-case
injection, so that counters follow chronological order and never change.
"""
